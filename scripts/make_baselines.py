#!/usr/bin/env python3
"""Write the exact baseline submissions for every setting in data/settings.json:

* best linear controller (Witsenhausen 1968, Lemma 11), found by minimizing
  the closed-form cost  k^2 sigma^2 (lam - 1)^2 + lam^2 sigma^2 / (1 + lam^2 sigma^2);
* Witsenhausen's two-point design f(x) = sigma * sgn(x).

Both are dated to Witsenhausen's paper; "verified_on" is the day this repository first scored them.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import minimize_scalar

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from witsenhausen import SCHEMA  # noqa: E402

BASE_DATE = "1968-02-01"
VERIFIED_ON = "2026-11-17"
PORTED_BY = "H. Munif"


def linear_cost(lam, k, sigma):
    s2 = sigma * sigma
    return k * k * s2 * (lam - 1.0) ** 2 + lam * lam * s2 / (1.0 + lam * lam * s2)


def best_gain(k, sigma):
    lam = np.linspace(-0.5, 1.5, 400_001)
    J = linear_cost(lam, k, sigma)
    # the cost can have two local minima (near 0 and near 1): refine every
    # grid-local minimum and keep the best
    idx = np.where((J[1:-1] <= J[:-2]) & (J[1:-1] <= J[2:]))[0] + 1
    best = (math.inf, None)
    for i in idx:
        r = minimize_scalar(linear_cost, bounds=(lam[i - 1], lam[i + 1]), args=(k, sigma),
                            method="bounded", options={"xatol": 1e-14})
        if r.fun < best[0]:
            best = (float(r.fun), float(r.x))
    return best[1], best[0]


def write(path: Path, sub: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(sub, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def main():
    settings = json.loads((ROOT / "data" / "settings.json").read_text(encoding="utf-8"))["settings"]
    for s in settings:
        k, sigma, sid = s["k"], s["sigma"], s["id"]
        lam, J = best_gain(k, sigma)
        write(ROOT / "submissions" / sid / "affine-optimal.json", {
            "schema": SCHEMA,
            "name": "Best linear controller",
            "short_name": "best linear controller",
            "authors": ["H. S. Witsenhausen"],
            "ported_by": PORTED_BY,
            "date": BASE_DATE,
            "verified_on": VERIFIED_ON,
            "setting": {"k": k, "sigma": sigma},
            "method": "Closed-form optimum over linear first controllers (Witsenhausen 1968, Lemma 11)",
            "source": {"kind": "paper", "url": "https://doi.org/10.1137/0306011"},
            "claimed_cost": round(J, 12),
            "notes": "Generated by scripts/make_baselines.py.",
            "controller": {"type": "linear", "gain": lam},
        })
        write(ROOT / "submissions" / sid / "witsenhausen-two-point.json", {
            "schema": SCHEMA,
            "name": r"Witsenhausen's two-point design, $f(x)=\sigma\,\mathrm{sgn}(x)$",
            "short_name": "two-point design",
            "authors": ["H. S. Witsenhausen"],
            "ported_by": PORTED_BY,
            "date": BASE_DATE,
            "verified_on": VERIFIED_ON,
            "setting": {"k": k, "sigma": sigma},
            "method": "The 1968 counterexample construction",
            "source": {"kind": "paper", "url": "https://doi.org/10.1137/0306011"},
            "notes": "Generated by scripts/make_baselines.py.",
            "controller": {"type": "piecewise_affine", "breakpoints": [0.0],
                           "intercepts": [-sigma, sigma], "slopes": [0.0, 0.0]},
        })
        print(f"{sid}: best linear gain {lam:.10f}, cost {J:.12f}")


if __name__ == "__main__":
    main()
